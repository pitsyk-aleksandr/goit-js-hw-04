console.log('category', getAllPropValues('category')); // []
console.log('name', getAllPropValues('name')); // ["Radar", "Scanner", "Droid", "Grip"]
console.log('price', getAllPropValues('price')); // [(1300, 2700, 400, 1200)]
console.log('quantity', getAllPropValues('quantity')); //  [(4, 3, 7, 9)]
